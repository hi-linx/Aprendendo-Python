# Calculo de média de notas de um aluno

nota1 = float(input('Digite a primeira nota: '))
nota2 = float(input('Digite a segunda nota: '))

print(f'Olá Aluno! \n A sua primeira nota é: {nota1}', end=' ')
print(f'e sua segunda nota é: {nota2}')
print('='*20)
print(f'A sua média é: {(nota1 + nota2)/2}')